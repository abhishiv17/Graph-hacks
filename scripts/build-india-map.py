"""Project the map data in data/geo into SVG paths for the web app (web/lib/india-map.ts).

Web Mercator, fitted so India fills the frame. Run again only if the GeoJSON changes:

    python scripts/build-india-map.py
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEO = ROOT / "data" / "geo"
OUT = ROOT / "web" / "lib" / "india-map.ts"
W = 1000           # viewBox width; height follows India's shape
PAD = 24


def merc(lon: float, lat: float) -> tuple[float, float]:
    return math.radians(lon), -math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))


def rings(geom: dict):
    t, c = geom["type"], geom["coordinates"]
    if t == "Polygon":
        yield from c
    elif t == "MultiPolygon":
        for poly in c:
            yield from poly
    elif t == "LineString":
        yield c
    elif t == "MultiLineString":
        yield from c


def load(name: str) -> list[dict]:
    d = json.loads((GEO / f"{name}.geojson").read_text(encoding="utf-8"))
    if "features" in d:
        return d["features"]
    return [{"geometry": g} for g in d.get("geometries", [d])]  # mapshaper -innerlines writes geometries


def main() -> None:
    india = load("india")
    xs, ys = [], []
    for f in india:
        for r in rings(f["geometry"]):
            for lon, lat in r:
                x, y = merc(lon, lat)
                xs.append(x)
                ys.append(y)
    k = (W - 2 * PAD) / (max(xs) - min(xs))
    H = round((max(ys) - min(ys)) * k + 2 * PAD)
    ox, oy = PAD - min(xs) * k, PAD - min(ys) * k

    def path(features: list[dict], close: bool) -> str:
        out = []
        for f in features:
            for r in rings(f["geometry"]):
                pts = [merc(lon, lat) for lon, lat in r]
                seg = "M" + "L".join(f"{x * k + ox:.1f},{y * k + oy:.1f}" for x, y in pts)
                out.append(seg + ("Z" if close else ""))
        return "".join(out)

    ts = f"""// Generated by scripts/build-india-map.py from data/geo (Natural Earth, public domain). Do not edit.
// India is drawn from India's point of view, matching India's official map.
export const MAP_W = {W};
export const MAP_H = {H};
const K = {k:.6f}, OX = {ox:.6f}, OY = {oy:.6f};

/** Web Mercator, in the same frame as the paths below. */
export function project(lon: number, lat: number): [number, number] {{
  const x = (lon * Math.PI) / 180, y = -Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
  return [x * K + OX, y * K + OY];
}}

export const INDIA = {json.dumps(path(india, True))};
export const STATE_LINES = {json.dumps(path(load("india_state_lines"), False))};
export const NEIGHBOURS = {json.dumps(path(load("neighbours"), True))};
"""
    OUT.write_text(ts, encoding="utf-8")
    print(f"Wrote {OUT} ({W} x {H}, {OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
